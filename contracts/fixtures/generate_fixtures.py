def build_ai_fact_bundle_fixture(symbol: str, bars_resp: dict, fundamentals_resp: dict, eval_resp: dict) -> dict:
    last_bar = bars_resp["bars"][-1]
    prev_bar = bars_resp["bars"][-2]
    closes = [b["close"] for b in bars_resp["bars"][-20:]]
    up_days = sum(1 for i in range(1, len(closes)) if closes[i] >= closes[i - 1])
    down_days = len(closes) - 1 - up_days

    money_flow = MoneyFlowBlock(
        accumulation_distribution_line=round(sum(closes), 2),
        on_balance_volume=float(sum(b["volume"] for b in bars_resp["bars"][-20:])),
        up_down_volume_ratio=round((up_days + 1) / (down_days + 1), 3),
        volume_at_price_concentration={
            "note": "OPEN ITEM shape; see contracts/OPEN_ITEMS.md",
            "buckets": [],
        },
        unusual_volume_flags=[],
        close_vs_vwap=None,
    )

    bundle = AIFactBundle(
        symbol=symbol,
        as_of_date=AS_OF_DATE,
        price_summary={
            "last_close": last_bar["close"],
            "prev_close": prev_bar["close"],
            "change_abs": round(last_bar["close"] - prev_bar["close"], 2),
            "change_pct": round((last_bar["close"] - prev_bar["close"]) / prev_bar["close"], 4),
            "last_volume": last_bar["volume"],
            "note": "OPEN ITEM shape; see contracts/OPEN_ITEMS.md",
        },
        indicators={
            "note": "OPEN ITEM shape; see contracts/OPEN_ITEMS.md",
            "sma_20": round(sum(closes) / len(closes), 2),
        },
        money_flow=money_flow,
        strategy_results=[StrategyEvaluationResult(**eval_resp["results"][0])],
        financial_summary={
            "note": "OPEN ITEM shape; see contracts/OPEN_ITEMS.md",
            "latest_revenue": fundamentals_resp["observations"][-2]["value"],
            "latest_net_income": fundamentals_resp["observations"][-1]["value"],
        },
        levels=Levels(**eval_resp["results"][0]["levels"]),
        data_quality={
            "freshness_status": "current",
            "warnings": [SYNTHETIC_WARNING],
        },
        sources=["https://vnstock.example/placeholder"],
        calculation_definitions=[
            "sma_20: simple moving average of close over the trailing 20 trading days.",
        ],
    )
    return json.loads(bundle.model_dump_json())


