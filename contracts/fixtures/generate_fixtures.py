def trading_dates(end: date, n: int) -> list[date]:
    """Business days ending at `end`, most recent last.

    Does not exclude Vietnamese public holidays (only weekends), since this
    is synthetic fixture data, not a real trading calendar. WP1's real
    FData adapter must use the actual file dates, not this approximation.
    """
    out: list[date] = []
    d = end
    while len(out) < n:
        if d.weekday() < 5:  # Mon-Fri
            out.append(d)
        d -= timedelta(days=1)
    out.reverse()
    return out


def synth_bars(
    symbol: str,
    exchange: str,
    anchor_close: float,
    anchor_open: float,
    anchor_high: float,
    anchor_low: float,
    anchor_volume: int,
    seed: int,
    n: int = N_BARS,
) -> list[dict]:
    rng = random.Random(seed)
    dates = trading_dates(AS_OF_DATE, n)

    # Build the close-price path backward from the anchor (last) day so the
    # final bar can equal the anchor exactly, then walk forward to derive
    # open/high/low/volume for every bar including the anchor day.
    closes = [0.0] * n
    closes[-1] = anchor_close
    for i in range(n - 2, -1, -1):
        pct = rng.gauss(0, 0.016)
        pct = max(min(pct, 0.07), -0.07)  # crude daily move cap
        prev_close = closes[i + 1] / (1 + pct)
        closes[i] = max(round(prev_close, 2), 1.0)

    bars = []
    prev_close = closes[0] * (1 - rng.gauss(0, 0.01))
    for i, d in enumerate(dates):
        close = closes[i]
        if i == n - 1:
            o, h, low, vol = anchor_open, anchor_high, anchor_low, anchor_volume
        else:
            o = round(prev_close * (1 + rng.gauss(0, 0.004)), 2)
            spread = abs(rng.gauss(0, 0.012)) * close
            h = round(max(o, close) + spread, 2)
            low = round(max(min(o, close) - spread, 0.1), 2)
            vol = int(max(rng.gauss(3_000_000, 1_200_000), 50_000))
        bars.append(
            {
                "symbol": symbol,
                "exchange": exchange,
                "security_type": "equity",
                "timeframe": "1D",
                "trading_date": d.isoformat(),
                "timezone": "Asia/Ho_Chi_Minh",
                "open": o,
                "high": h,
                "low": low,
                "close": close,
                "volume": vol,
                "adjustment_status": "adjusted_unknown_method",
                "source": "Fialda FData",
                "source_file": f"C:\\FDATA\\AmiBroker\\EOD\\stock\\{symbol}.dat",
                "ingested_at": INGESTED_AT.isoformat(),
                "quality_status": "valid",
            }
        )
        prev_close = close
    return bars


def provenance(warnings: list[str] | None = None) -> Provenance:
    return Provenance(
        as_of_date=AS_OF_DATE,
        data_version=DATA_VERSION,
        source="Fialda FData",
        freshness_status="current",
        warnings=warnings or [],
    )


def build_bars_fixture(symbol: str, exchange: str, **kw) -> dict:
    bars = synth_bars(symbol, exchange, **kw)
    resp = BarsResponse(
        symbol=symbol,
        timeframe="1D",
        bars=bars,
        provenance=provenance([SYNTHETIC_WARNING]),
    )
    return json.loads(resp.model_dump_json())


